export const SHOTS = Object.freeze(script.map(([start,set,action,camera,cast],index)=>Object.freeze({
  index,start,end:script[index+1]?.[0]??DURATION,set,action,camera,cast:Object.freeze(cast),
})));

export function wrapTime(seconds) {
  if(!Number.isFinite(seconds))throw new TypeError('Animation time must be finite');
  return Math.round(((seconds%DURATION+DURATION)%DURATION)*1e9)/1e9%DURATION;
}

export function stateAt(seconds) {
  const time=wrapTime(seconds);
  const shot=SHOTS.find(s=>time<s.end)??SHOTS[0];
  const local=time-shot.start;
  return {time,shot,local,progress:local/(shot.end-shot.start),
    loopBlend:time>=SEAM_START?(time-SEAM_START)/(DURATION-SEAM_START):0};
}
